#!/usr/bin/env bash
# Renders prometheus.gen.yml from .env and (re)starts the stack on the system
# Docker engine (not Docker Desktop's VM, so host networking reaches the worker).
#
#   ./up.sh            # render + up -d
#   ./up.sh logs -f    # any other docker compose subcommand
set -euo pipefail
cd "$(dirname "$0")"
[[ -f .env ]] || { echo "copy .env.example to .env first" >&2; exit 1; }
while IFS= read -r line; do # settings added to .env.example since .env was made
  k=${line%%=*}
  if [[ $line == *=* && $line != \#* ]] && ! grep -q "^$k=" .env; then echo "$line" >>.env; fi
done <.env.example
for k in SEARXNG_SECRET RDNAMCP_TOKEN NTFY_TOPIC; do # generate missing secrets once
  if ! grep -q "^$k=." .env; then
    v=$(openssl rand -hex 24)
    [[ $k == NTFY_TOPIC ]] && v=rdna-alerts-$(openssl rand -hex 6)
    if grep -q "^$k=" .env; then sed -i "s|^$k=.*|$k=$v|" .env; else echo "$k=$v" >>.env; fi
  fi
done
chmod 600 .env
[[ -x bin/rdnamcp ]] || { echo "bin/rdnamcp missing: GOOS=linux GOARCH=amd64 CGO_ENABLED=0 go build -o deploy/sff/bin/rdnamcp ./cmd/rdnamcp" >&2; exit 1; }
set -a; source .env; set +a
dc() { docker --context "${DOCKER_CONTEXT:-default}" compose "$@"; }

if [[ $# -gt 0 ]]; then dc "$@"; exit; fi

{
  cat <<EOF
# Generated by up.sh from .env; edit those, not this.
global:
  scrape_interval: 15s
  scrape_timeout: 5s

rule_files: [/etc/prometheus/rules.yml]

scrape_configs:
  - job_name: gateway
    static_configs:
      - targets: ["$GATEWAY"]
        labels: {host: gateway}

  - job_name: worker
    static_configs:
      - targets: ["$LOCAL_WORKER_ADDR"]
        labels: {worker: "$LOCAL_WORKER"}
      - targets: ["$BIND_IP:8082"]
        labels: {worker: "$CPU_WORKER"}
      - targets: ["${EMBED_ADDR:-$BIND_IP:8083}"]
        labels: {worker: "embed"}
      - targets: ["${RERANK_ADDR:-$BIND_IP:8084}"]
        labels: {worker: "rerank"}

  - job_name: mcp
    static_configs:
      - targets: ["$BIND_IP:8090"]

  - job_name: qdrant
    static_configs:
      - targets: ["127.0.0.1:6333"]

  - job_name: envoy
    scrape_interval: 30s
    scrape_timeout: 15s
    static_configs:
      - targets: ["127.0.0.1:9110"]
EOF
  for w in $RELAYED_WORKERS; do
    cat <<EOF
  - job_name: worker-$w
    metrics_path: /metrics/workers/$w
    static_configs:
      - targets: ["$GATEWAY"]
        labels: {worker: "$w"}
    metric_relabel_configs: [{target_label: job, replacement: worker}]
EOF
  done
  cat <<EOF

  - job_name: node
    static_configs:
      - targets: ["127.0.0.1:9101"]
        labels: {host: "$(hostname)"}
EOF
  for n in ${EXTRA_NODES:-}; do # name=host:port node_exporters on other boxes
    cat <<EOF

  - job_name: node-${n%%=*}
    static_configs:
      - targets: ["${n#*=}"]
        labels: {host: "${n%%=*}"}
    metric_relabel_configs: [{target_label: job, replacement: node}]
EOF
  done
  if [[ "${GATEWAY_HOST_METRICS:-}" == yes ]]; then # the gateway host's sensors (LibreHardwareMonitor)
    cat <<EOF

  - job_name: desktop-host
    metrics_path: /metrics/host
    static_configs:
      - targets: ["$GATEWAY"]
        labels: {host: desktop}
EOF
  fi
  if [[ -n "${WINDOWS_EXPORTER:-}" ]]; then
    cat <<EOF

  - job_name: windows
    static_configs:
      - targets: ["$WINDOWS_EXPORTER"]
EOF
  fi
} >prometheus/prometheus.gen.yml

# Power, energy and cost: per-box draw from sensors plus estimated overheads.
num() { [[ ${1:-} =~ ^[0-9]+([.][0-9]+)?$ ]] && echo "$1" || echo "$2"; }
eff=$(num "${PSU_EFFICIENCY:-}" 0.88) jeff=$(num "${JETSON_ADAPTER_EFFICIENCY:-}" 0.88)
cat >prometheus/rules.gen.yml <<EOF
# Generated by up.sh from .env; edit those, not this.
groups:
  - name: lab-energy
    interval: 30s
    rules:
      # Desktop: GPU + CPU package from LibreHardwareMonitor, plus the rest of the box.
      - record: lab:power_watts
        labels: {box: desktop}
        expr: (sum(lhm_gpuamd_power_watts{sensorName="GPU Package"}) + sum(lhm_cpu_power_watts{sensorName="Package"}) + $(num "${DESKTOP_OVERHEAD_W:-}" 45)) / $eff
      # Server box: the discrete GPU is measured; its CPU has no readable power counter, so scale idle..max by load.
      - record: lab:power_watts
        labels: {box: server}
        expr: >-
          (sum(node_hwmon_power_average_watt and on (chip) node_hwmon_sensor_label{label="junction"})
          + $(num "${SFF_CPU_IDLE_W:-}" 20) + ($(num "${SFF_CPU_MAX_W:-}" 110) - $(num "${SFF_CPU_IDLE_W:-}" 20)) * (1 - avg(rate(node_cpu_seconds_total{mode="idle",host!="jetson"}[2m])))
          + $(num "${SFF_OVERHEAD_W:-}" 20)) / $eff
      # Jetson: whole-board input (VDD_IN), plus its power adapter's loss.
      - record: lab:power_watts
        labels: {box: jetson}
        expr: sum(node_hwmon_in_volts{host="jetson",sensor="in1"}) * sum(node_hwmon_curr_amps{host="jetson",sensor="curr1"}) / $jeff
      - record: lab:power_watts:sum
        expr: sum(lab:power_watts)
      # All-in \$/kWh: summer rate June-September, winter rate otherwise.
      - record: lab:electric_rate_usd_per_kwh
        expr: (vector($(num "${ELECTRIC_RATE_SUMMER:-}" 0)) and on () (month() >= 6 and month() <= 9)) or vector($(num "${ELECTRIC_RATE_WINTER:-}" 0))
      - record: lab:cost_usd_per_hour
        expr: lab:power_watts:sum / 1000 * on () lab:electric_rate_usd_per_kwh
      # Share of the house's draw covered by solar right now (needs consumption CTs).
      - record: lab:solar_share
        expr: clamp_max(envoy_production_watts / (envoy_consumption_watts > 0), 1)
      - record: lab:solar_watts
        expr: lab:power_watts:sum * on () lab:solar_share
EOF
mkdir -p secrets && chmod 700 secrets

dc up -d --remove-orphans
dc ps --format '{{.Service}}\t{{.Status}}'
